package app

import (
	"context"
	"fmt"
	"sort"
	"strings"

	"sigs.k8s.io/yaml"

	"github.com/flanksource/commons-db/models"
	"github.com/flanksource/commons-db/query"
	"github.com/flanksource/commons-db/query/profilestore"
)

// connectionLogsPrefix names the profiles connectionLogProfiles generates. The
// overlay treats every name carrying it as virtual, so a stored profile cannot
// take one and later be shadowed by a connection of the same name.
const connectionLogsPrefix = "Logs: "

// connectionLogsTemplate is everything a generated profile shares: the shape of
// profiles/k8s-pod-logs.yaml without its target, which the connection supplies.
// The time, namespace, workload and label pickers are generated by the k8s
// provider for every profile it backs.
const connectionLogsTemplate = `
render: logs
provider:
  type: k8s
limits:
  pageSize: 500
  maxPageSize: 500
processors:
  - use: logs.dedupe
columns:
  - name: timestamp
    label: Time
    type: datetime
  - name: namespace
    label: Namespace
  - name: pod
    label: Pod
  - name: container
    label: Container
  - name: count
    label: Seen
    type: number
  - name: message
    label: Message
`

// connectionLogProfiles is a read-only profile store holding one logs profile
// per Kubernetes connection, which is the view a Kubernetes connection opens on.
// A connection whose `namespace` property is set is restricted to it.
type connectionLogProfiles struct {
	list func(types string) ([]*models.Connection, error)
}

func (s connectionLogProfiles) List(context.Context) ([]query.Profile, error) {
	connections, err := s.list(models.ConnectionTypeKubernetes)
	if err != nil {
		return nil, fmt.Errorf("list Kubernetes connections for their logs profiles: %w", err)
	}
	profiles := make([]query.Profile, 0, len(connections))
	for _, connection := range connections {
		if connection.Type != models.ConnectionTypeKubernetes {
			continue
		}
		profile, err := connectionLogsProfile(connection)
		if err != nil {
			return nil, err
		}
		profiles = append(profiles, profile)
	}
	sort.Slice(profiles, func(i, j int) bool { return profiles[i].Name < profiles[j].Name })
	return profiles, nil
}

func (s connectionLogProfiles) Get(ctx context.Context, name string) (query.Profile, error) {
	profiles, err := s.List(ctx)
	if err != nil {
		return query.Profile{}, err
	}
	for _, profile := range profiles {
		if profile.Name == name {
			return profile, nil
		}
	}
	return query.Profile{}, fmt.Errorf("profile %q not found: no Kubernetes connection %q", name, strings.TrimPrefix(name, connectionLogsPrefix))
}

func (s connectionLogProfiles) Peek(ctx context.Context, name string) (query.Profile, error) {
	return s.Get(ctx, name)
}

func (connectionLogProfiles) IsVirtual(name string) bool {
	return strings.HasPrefix(name, connectionLogsPrefix)
}

func (connectionLogProfiles) Save(_ context.Context, profile query.Profile) error {
	return fmt.Errorf("profile %q is generated from its Kubernetes connection and is read-only", profile.Name)
}

func (connectionLogProfiles) Update(_ context.Context, name string, _ query.Profile, _ profilestore.UpdateOptions) error {
	return fmt.Errorf("profile %q is generated from its Kubernetes connection and is read-only", name)
}

func (connectionLogProfiles) Delete(_ context.Context, name string) error {
	return fmt.Errorf("profile %q is generated from its Kubernetes connection and is read-only", name)
}

func connectionLogsProfile(connection *models.Connection) (query.Profile, error) {
	var profile query.Profile
	if err := yaml.Unmarshal([]byte(connectionLogsTemplate), &profile); err != nil {
		return query.Profile{}, fmt.Errorf("decode the connection logs profile template: %w", err)
	}
	reference := connection.Name
	if connection.Namespace != "" {
		reference = connection.Namespace + "/" + connection.Name
	}
	profile.Name = connectionLogsPrefix + reference
	profile.Provider.Connection = "connection://" + reference
	profile.Virtual, profile.ReadOnly = true, true
	if namespace := strings.TrimSpace(connection.Properties["namespace"]); namespace != "" {
		profile.Query = "namespace=" + namespace
	}
	return profile, nil
}
